function getLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && I18N[saved]) return saved;
  } catch (e) {}
  return 'lv';
}

function t(key) {
  const lang = getLang();
  const dict = I18N[lang] || I18N.lv;
  return dict[key] || I18N.lv[key] || key;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  try {
    localStorage.setItem('lang', lang);
  } catch (e) {}
  applyLanguage();
}

function applyLanguage() {
  const lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (!translation) return;

    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = translation;
    } else if (el.children.length === 0) {
      el.textContent = translation;
    } else {
      const textNode = Array.from(el.childNodes).find(n => n.nodeType === Node.TEXT_NODE);
      if (textNode) {
        textNode.textContent = translation;
      } else {
        el.insertBefore(document.createTextNode(translation), el.firstChild);
      }
    }
  });
}

if (typeof globalThis !== 'undefined') {
  globalThis.I18N = I18N;
  globalThis.getLang = getLang;
  globalThis.t = t;
  globalThis.setLang = setLang;
  globalThis.applyLanguage = applyLanguage;
}
